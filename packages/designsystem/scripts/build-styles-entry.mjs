// Writes dist/styles.css, the single CSS entry consumers import.
//
// The JS bundle carries no CSS import: esbuild strips relative CSS imports from
// the JS output and emits them as sibling .css files, and a JS file that imports
// CSS cannot be loaded by Node at all (SSR, and the CJS build). So CSS delivery is
// an explicit import, the same contract Designsystemet itself uses.
//
// Cascade order matters and is baked in here rather than left to the consumer:
//   1. Designsystemet component CSS, in @layer ds
//   2. DIBK theme tokens (--ds-*), unlayered so they beat DS defaults
//   3. DIBK base + overrides + component CSS (index.css), unlayered so the
//      overrides beat @layer ds without specificity hacks
//   4. Layout primitive CSS (layout.css), the l-* namespace, no conflicts
//
// Designsystemet's CSS is referenced by bare specifier, NOT inlined, so it
// resolves from the consumer's node_modules at their build time. It is a peer
// dependency: inlining a copy here would freeze one version of the CSS while the
// consumer floats the React package, which is exactly the skew peer deps prevent.
//
// The brand font is deliberately absent: it lives in dist/fonts.css, so an app
// that supplies its own typeface imports this file alone.
import { mkdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const distDir = resolve(here, "../dist");

const css = `/* dibk-designsystemet - generated by scripts/build-styles-entry.mjs. Do not edit. */
@import "@digdir/designsystemet-css";
@import "./theme.css";
@import "./index.css";
@import "./layout.css";
`;

await mkdir(distDir, { recursive: true });
await writeFile(resolve(distDir, "styles.css"), css, "utf8");
