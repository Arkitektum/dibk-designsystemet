// Writes dist/fonts.css, the optional brand-font entry consumers import.
//
// Derived from @fontsource/poppins rather than hand-authored, so the
// unicode-range values stay exactly as upstream defines them. Two transforms:
//
//   1. Drop the devanagari subset. Poppins ships latin, latin-ext and devanagari
//      per weight; a Norwegian app never renders devanagari, and unicode-range
//      means the browser never downloads it, but it still lands in every
//      consumer's build output. Keeping latin-ext covers foreign names.
//   2. Drop the .woff fallback and keep .woff2 only. woff2 has been universally
//      supported since 2016, and the fallback doubles the emitted font files.
//
// The url()s become bare specifiers so they resolve from the consumer's own
// @fontsource/poppins at their build time: it is a peer dependency, so inlining
// or copying the files here would pin one version of the font while the consumer
// floats it. Bundlers resolve bare specifiers inside url() (verified with Vite).
//
// The @font-face declarations are useless without the font family being
// referenced, which is what dist/theme.css does via --ds-font-family. Apps that
// supply their own font skip this file and import styles.css alone.
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const WEIGHTS = [300, 400, 500, 600, 700];
const SKIP_SUBSETS = new Set(["devanagari"]);

const here = dirname(fileURLToPath(import.meta.url));
const distDir = resolve(here, "../dist");
const require = createRequire(import.meta.url);
const fontsourceDir = dirname(require.resolve("@fontsource/poppins/package.json"));

const blocks = [];
for (const weight of WEIGHTS) {
  const css = await readFile(resolve(fontsourceDir, `${weight}.css`), "utf8");
  const found = css.matchAll(/\/\* poppins-(\S+?)-\d+-normal \*\/\s*(@font-face \{.*?\n\})/gs);
  for (const [, subset, block] of found) {
    if (SKIP_SUBSETS.has(subset)) continue;
    blocks.push(
      block
        // keep woff2, drop the woff fallback that follows it
        .replace(/src:[^;]+;/, (src) => {
          const woff2 = src.match(/url\(\.\/files\/(\S+?\.woff2)\)\s*format\('woff2'\)/);
          if (!woff2) throw new Error(`No woff2 source in ${subset}-${weight}`);
          return `src: url("@fontsource/poppins/files/${woff2[1]}") format('woff2');`;
        }),
    );
  }
}

if (blocks.length !== WEIGHTS.length * 2) {
  throw new Error(`Expected ${WEIGHTS.length * 2} @font-face blocks, got ${blocks.length}`);
}

const header = "/* dibk-designsystemet - generated by scripts/build-fonts-entry.mjs. Do not edit. */";
await mkdir(distDir, { recursive: true });
await writeFile(resolve(distDir, "fonts.css"), `${header}\n${blocks.join("\n")}\n`, "utf8");
